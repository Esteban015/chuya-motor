import type { BenchmarkSummary, BenchmarkResult } from './types'
import { COST_DISCLAIMER } from './cost'

export interface ReportOptions {
  includeResultDetails?: boolean
  omitTraces?: boolean
}

/**
 * Serializes the benchmark summary to JSON.
 * Strips credentials and traces by default.
 */
export function toJSON(summary: BenchmarkSummary, options: ReportOptions = {}): string {
  const sanitized = sanitizeSummary(summary, options)
  return JSON.stringify(sanitized, null, 2)
}

/**
 * Generates a human-readable Markdown report.
 */
export function toMarkdown(summary: BenchmarkSummary, options: ReportOptions = {}): string {
  const lines: string[] = []

  lines.push(`# Benchmark Report — ${summary.runId}`)
  lines.push('')
  lines.push(`**Mode:** \`${summary.mode}\``)
  lines.push(`**Started:** ${summary.startedAt}`)
  lines.push(`**Completed:** ${summary.completedAt}`)
  lines.push('')
  lines.push('## Summary')
  lines.push('')
  lines.push(`| Metric | Value |`)
  lines.push(`|--------|-------|`)
  lines.push(`| Total scenarios | ${summary.total} |`)
  lines.push(`| Passed | ${summary.passed} |`)
  lines.push(`| Failed | ${summary.failed} |`)
  lines.push(`| Errors | ${summary.errors} |`)
  lines.push(`| Pass rate | ${(summary.passRate * 100).toFixed(1)}% |`)
  lines.push(`| Human review required | ${summary.humanReviewRequired} |`)
  lines.push(`| Total tokens used | ${summary.totalTokensUsed} |`)

  if (summary.estimatedCostUsd !== null) {
    lines.push(`| Estimated cost (USD) | $${summary.estimatedCostUsd.toFixed(6)} |`)
  } else {
    lines.push(`| Estimated cost (USD) | Unknown model |`)
  }

  lines.push('')
  lines.push(`> _${COST_DISCLAIMER}_`)
  lines.push('')
  lines.push('## Latency')
  lines.push('')
  lines.push(`| Percentile | Duration |`)
  lines.push(`|------------|----------|`)
  lines.push(`| p50 | ${summary.latencyMs.p50.toFixed(0)}ms |`)
  lines.push(`| p95 | ${summary.latencyMs.p95.toFixed(0)}ms |`)
  lines.push(`| max | ${summary.latencyMs.max.toFixed(0)}ms |`)
  lines.push('')
  lines.push('## Results by Category')
  lines.push('')
  lines.push(`| Category | Total | Passed | Failed | Pass Rate | Avg Latency |`)
  lines.push(`|----------|-------|--------|--------|-----------|-------------|`)

  for (const cat of summary.byCategory) {
    lines.push(
      `| ${cat.category} | ${cat.total} | ${cat.passed} | ${cat.failed} | ${(cat.passRate * 100).toFixed(1)}% | ${cat.avgDurationMs}ms |`,
    )
  }

  if (options.includeResultDetails) {
    lines.push('')
    lines.push('## Scenario Results')
    lines.push('')
    for (const result of summary.results) {
      lines.push(renderResultSection(result, options))
    }
  }

  lines.push('')
  lines.push('---')
  lines.push(`_Generated by Chuya Motor Benchmark Platform_`)

  return lines.join('\n')
}

function renderResultSection(result: BenchmarkResult, options: ReportOptions): string {
  const icon = result.passed ? '✅' : '❌'
  const lines: string[] = []
  lines.push(`### ${icon} ${result.scenarioId}`)
  lines.push('')
  lines.push(`- **Category:** ${result.category}`)
  lines.push(`- **Severity:** ${result.severity}`)
  lines.push(`- **Duration:** ${result.durationMs}ms`)
  lines.push(`- **Tokens used:** ${result.tokensUsed}`)

  if (result.error) {
    lines.push(`- **Error:** \`${result.error}\``)
  }

  if (result.deterministicChecks.length > 0) {
    lines.push('')
    lines.push('**Deterministic checks:**')
    for (const check of result.deterministicChecks) {
      const icon2 = check.passed ? '✅' : '❌'
      lines.push(`- ${icon2} \`${check.assertion}\` (actual: \`${check.actual}\`)`)
    }
  }

  if (!result.securityCheck.passed) {
    lines.push('')
    lines.push('**Security violations:**')
    for (const v of result.securityCheck.violations) {
      lines.push(`- ⚠️ ${v}`)
    }
  }

  if (result.requiresHumanReview && result.reviewNotes) {
    lines.push('')
    lines.push(`**Human review notes:** ${result.reviewNotes}`)
  }

  if (!options.omitTraces && result.output?.traces && result.output.traces.length > 0) {
    lines.push('')
    lines.push(`<details><summary>Traces (${result.output.traces.length})</summary>`)
    lines.push('')
    lines.push('```json')
    lines.push(JSON.stringify(result.output.traces, null, 2))
    lines.push('```')
    lines.push('</details>')
  }

  lines.push('')
  return lines.join('\n')
}

function sanitizeSummary(summary: BenchmarkSummary, options: ReportOptions): unknown {
  const credentialPatterns = [
    /sk-ant-[A-Za-z0-9_-]+/g,
    /Bearer [A-Za-z0-9_.-]+/g,
    /LLM_API_KEY/g,
    /GEMINI_API_KEY/g,
    /AIza[A-Za-z0-9_-]{20,}/g,
  ]

  const serialized = JSON.stringify(summary)
  let sanitized = serialized
  for (const pattern of credentialPatterns) {
    sanitized = sanitized.replace(pattern, '[REDACTED]')
  }

  const parsed = JSON.parse(sanitized) as BenchmarkSummary

  if (options.omitTraces) {
    parsed.results = parsed.results.map((r) => ({
      ...r,
      output: r.output ? { ...r.output, traces: [] } : null,
    }))
  }

  if (!options.includeResultDetails) {
    parsed.results = []
  }

  return parsed
}
